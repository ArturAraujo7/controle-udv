-- ============================================================
-- 5. Funções de escopo
-- ============================================================
CREATE OR REPLACE FUNCTION public.meu_nucleo()
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT nucleo_id FROM public.profiles WHERE id = auth.uid()
$$;

CREATE OR REPLACE FUNCTION public.minha_regiao()
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE(p.regiao_id, n.regiao_id)
  FROM public.profiles p
  LEFT JOIN public.nucleos n ON n.id = p.nucleo_id
  WHERE p.id = auth.uid()
$$;

CREATE OR REPLACE FUNCTION public.eh_central()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND status = 'ativo' AND role::text = 'central'
  )
$$;

-- Registros novos herdam o núcleo de quem cria (ou do registro pai)
CREATE OR REPLACE FUNCTION public.definir_nucleo()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.nucleo_id IS NULL THEN
    NEW.nucleo_id := public.meu_nucleo();
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.herdar_nucleo_sessao()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.nucleo_id IS NULL THEN
    SELECT nucleo_id INTO NEW.nucleo_id FROM public.sessoes WHERE id = NEW.id_sessao;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.herdar_nucleo_membro()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.nucleo_id IS NULL THEN
    SELECT nucleo_id INTO NEW.nucleo_id FROM public.membros WHERE id = NEW.membro_id;
  END IF;
  RETURN NEW;
END;
$$;

