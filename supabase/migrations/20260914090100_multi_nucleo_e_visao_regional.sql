CREATE TRIGGER trg_criar_configuracoes_nucleo
  AFTER INSERT ON public.nucleos
  FOR EACH ROW EXECUTE FUNCTION public.criar_configuracoes_nucleo();

INSERT INTO public.configuracoes (nucleo_id)
SELECT id FROM public.nucleos
ON CONFLICT (nucleo_id) DO NOTHING;

