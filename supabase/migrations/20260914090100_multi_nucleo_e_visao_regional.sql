-- Guardião — vários núcleos no mesmo banco e visão regional do Mestre Central.
--
-- • Cada registro passa a pertencer a um núcleo (nucleo_id); os dados existentes
--   ficam no núcleo criado a partir das configurações atuais.
-- • Usuários de núcleo leem e escrevem só o próprio núcleo (RLS).
-- • O administrador passa a ser administrador geral: gerencia regiões, núcleos,
--   usuários, configurações e listas de todos os núcleos.
-- • O Mestre Central não pertence a núcleo; lê os dados da própria região pela
--   função dados_regionais(), sem permissão de escrita.
-- • Configurações são por núcleo; listas do sistema são por região.

-- ============================================================
-- 1. Regiões e núcleos
-- ============================================================
CREATE TABLE IF NOT EXISTS public.regioes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.nucleos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  regiao_id bigint NOT NULL REFERENCES public.regioes(id),
  cidade text,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (regiao_id, nome)
);

-- Região e núcleo iniciais, a partir das configurações existentes
DO $$
DECLARE
  v_regiao bigint;
  v_nome text;
  v_nome_regiao text;
  v_cidade text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.nucleos) THEN
    SELECT nucleo_nome, nucleo_regiao, nucleo_cidade
      INTO v_nome, v_nome_regiao, v_cidade
      FROM public.configuracoes
      LIMIT 1;

    INSERT INTO public.regioes (nome)
    VALUES (COALESCE(NULLIF(trim(v_nome_regiao), ''), 'Região principal'))
    RETURNING id INTO v_regiao;

    INSERT INTO public.nucleos (nome, regiao_id, cidade)
    VALUES (COALESCE(NULLIF(trim(v_nome), ''), 'Núcleo Jardim Real'), v_regiao, NULLIF(trim(v_cidade), ''));
  END IF;
END $$;

-- ============================================================
-- 2. nucleo_id em todas as tabelas de dados
-- ============================================================
DO $$
DECLARE
  t text;
  v_nucleo bigint := (SELECT min(id) FROM public.nucleos);
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'sessoes', 'preparos', 'saidas', 'consumos_sessao', 'membros',
    'membros_graus_historico', 'leituras', 'historias', 'visitantes'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS nucleo_id bigint REFERENCES public.nucleos(id)', t);
    EXECUTE format('UPDATE public.%I SET nucleo_id = %s WHERE nucleo_id IS NULL', t, v_nucleo);
    EXECUTE format('ALTER TABLE public.%I ALTER COLUMN nucleo_id SET NOT NULL', t);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I (nucleo_id)', t || '_nucleo_id_idx', t);
  END LOOP;
END $$;

-- Usuários: núcleo (usuários de núcleo) ou região (Mestre Central)
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS nucleo_id bigint REFERENCES public.nucleos(id);
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS regiao_id bigint REFERENCES public.regioes(id);
UPDATE public.profiles
SET nucleo_id = (SELECT min(id) FROM public.nucleos)
WHERE nucleo_id IS NULL AND regiao_id IS NULL;

ALTER TABLE public.activity_logs ADD COLUMN IF NOT EXISTS nucleo_id bigint;
UPDATE public.activity_logs SET nucleo_id = (SELECT min(id) FROM public.nucleos) WHERE nucleo_id IS NULL;
CREATE INDEX IF NOT EXISTS activity_logs_nucleo_idx ON public.activity_logs (nucleo_id, created_at DESC);

-- ============================================================
-- 3. Configurações por núcleo
-- ============================================================
ALTER TABLE public.configuracoes ADD COLUMN IF NOT EXISTS nucleo_id bigint REFERENCES public.nucleos(id) ON DELETE CASCADE;
UPDATE public.configuracoes SET nucleo_id = (SELECT min(id) FROM public.nucleos) WHERE nucleo_id IS NULL;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'configuracoes' AND column_name = 'id'
  ) THEN
    ALTER TABLE public.configuracoes DROP CONSTRAINT IF EXISTS configuracoes_pkey;
    ALTER TABLE public.configuracoes DROP COLUMN id;
    ALTER TABLE public.configuracoes ALTER COLUMN nucleo_id SET NOT NULL;
    ALTER TABLE public.configuracoes ADD PRIMARY KEY (nucleo_id);
  END IF;
END $$;

-- Nome, região e cidade agora ficam na tabela nucleos
ALTER TABLE public.configuracoes DROP COLUMN IF EXISTS nucleo_nome;
ALTER TABLE public.configuracoes DROP COLUMN IF EXISTS nucleo_regiao;
ALTER TABLE public.configuracoes DROP COLUMN IF EXISTS nucleo_cidade;

