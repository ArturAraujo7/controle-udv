RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.configuracoes (nucleo_id) VALUES (NEW.id) ON CONFLICT (nucleo_id) DO NOTHING;
  RETURN NEW;
END;
$$;

