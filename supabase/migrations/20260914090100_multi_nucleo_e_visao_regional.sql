-- ============================================================
-- 6. Regras de acesso (RLS)
-- ============================================================
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'sessoes', 'preparos', 'saidas', 'consumos_sessao', 'membros',
    'membros_graus_historico', 'leituras', 'historias', 'visitantes'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "Enable read access for all authenticated users" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "Enable write access for editors" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "Users can read all membros" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "Leitura para autenticados" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "Escrita para editores" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "Leitura do próprio núcleo" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "Escrita por editores do núcleo" ON public.%I', t);

    EXECUTE format(
      'CREATE POLICY "Leitura do próprio núcleo" ON public.%I FOR SELECT TO authenticated
       USING (nucleo_id = public.meu_nucleo())', t);
    EXECUTE format(
      'CREATE POLICY "Escrita por editores do núcleo" ON public.%I FOR ALL TO authenticated
       USING (public.can_edit() AND nucleo_id = public.meu_nucleo())
       WITH CHECK (public.can_edit() AND nucleo_id = public.meu_nucleo())', t);
  END LOOP;
END $$;

