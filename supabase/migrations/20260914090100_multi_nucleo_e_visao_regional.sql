  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- ============================================================
-- 7. Proteção de papel, núcleo e região dos usuários
-- ============================================================
CREATE OR REPLACE FUNCTION public.proteger_campos_profile()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NOT NULL
     AND NOT public.is_admin()
     AND (NEW.role IS DISTINCT FROM OLD.role
          OR NEW.status IS DISTINCT FROM OLD.status
          OR NEW.membro_id IS DISTINCT FROM OLD.membro_id
          OR NEW.nucleo_id IS DISTINCT FROM OLD.nucleo_id
          OR NEW.regiao_id IS DISTINCT FROM OLD.regiao_id) THEN
    RAISE EXCEPTION 'Somente administradores podem alterar papel, situação, núcleo ou vínculo de usuários';
  END IF;
  RETURN NEW;
END;
$$;

DROP FUNCTION IF EXISTS public.admin_listar_usuarios();
CREATE FUNCTION public.admin_listar_usuarios()
RETURNS TABLE (
  id uuid,
  full_name text,
  email text,
  role public.user_role,
  status text,
  membro_id bigint,
  nucleo_id bigint,
  regiao_id bigint,
  criado_em timestamptz,
  ultimo_acesso timestamptz,
  provedor text
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Acesso negado';
  END IF;

  RETURN QUERY
  SELECT p.id, p.full_name, p.email, p.role, p.status, p.membro_id, p.nucleo_id, p.regiao_id,
         u.created_at, u.last_sign_in_at, (u.raw_app_meta_data->>'provider')::text
  FROM public.profiles p
  JOIN auth.users u ON u.id = p.id
  ORDER BY p.full_name NULLS LAST;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_listar_usuarios() FROM PUBLIC, anon;
